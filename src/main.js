function asyncOperationDemo(callback) {
  if (typeof callback !== 'function')
    throw new TypeError('callback must be a function')
  console.log('Перший виклик')
  return new Promise((resolve, reject) => {
    let failed = false
    const finish = operation => {
      if (failed)
        return false
      try {
        console.log(`Виконано ${operation}`)
        callback(operation)
        console.log(`Завершено виконання: ${operation}`)
        return true
      } catch (error) {
        failed = true
        reject(error)
        return false
      }
    }
    process.nextTick(() => finish('nextTick'))
    setImmediate(() => {
      if (!finish('setImmediate'))
        return
      setTimeout(() => { if (finish('setTimeout')) resolve() }, 0)
    })
    console.log('Останній виклик')
  })
}


export { asyncOperationDemo }
